#!/usr/bin/env bash
# Regenerate TOOLS.md and the tool count in README.md from the public server card.
# Source of truth: https://enterno.io/.well-known/mcp/server-card.json (public, no key needed).
# Usage: scripts/update-tools.sh   (needs bash, curl, jq; run from anywhere)
set -euo pipefail

CARD_URL="${CARD_URL:-https://enterno.io/.well-known/mcp/server-card.json}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TODAY="$(date -u +%Y-%m-%d)"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

curl -fsS --max-time 30 "$CARD_URL" -o "$TMP"
jq -e '.tools | type == "array" and length > 0' "$TMP" > /dev/null

COUNT="$(jq '.tools | length' "$TMP")"

{
  echo "# Tools"
  echo
  echo "Generated by \`scripts/update-tools.sh\` from the public server card"
  echo "<$CARD_URL> on $TODAY. Do not edit by hand."
  echo
  echo "For the live list with argument schemas, call \`tools/list\` with your API key."
  echo "The plan each tool needs is shown on <https://enterno.io/en/mcp-server>."
  echo
  echo "| Tool | What it does | Required arguments |"
  echo "|---|---|---|"
  jq -r '
    def esc: gsub("\\|"; "\\|") | gsub("[\r\n]+"; " ");
    .tools[]
    | "| `\(.name)` | \(.description // "" | esc) | \((.inputSchema.required // []) | map("`" + . + "`") | join(", ") | if . == "" then "—" else . end) |"
  ' "$TMP"
} > "$ROOT/TOOLS.md"

# Replace the marked count/date in README.md, nothing else.
sed -i -E "s|<!-- tools:count -->[^<]*<!-- /tools:count -->|<!-- tools:count -->${COUNT} tools (server card, ${TODAY})<!-- /tools:count -->|" "$ROOT/README.md"

echo "TOOLS.md: $COUNT tools from $CARD_URL"
